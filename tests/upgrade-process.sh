#!/usr/bin/env bash
# upgrade-process.sh — process-level test for the real `o3k` binary's
# upgrade/rollback state machine (issue #626, docs/plan/o3k-upgrade.md §13.2).
#
# Deterministic, rootless, and offline: everything the upgrade engine could
# touch is a private mktemp sandbox driven through the engine's sandbox
# overrides (O3K_UPGRADE_PREFIX / _BIN_DIR / _CONFIG_DIR / _DATA_DIR /
# _STATE_FILE / _BACKUP_DIR / _DOWNLOAD_DIR), PATH shims for systemctl /
# virsh / ip / df / ps / curl, loopback health shims on the standard
# 127.0.0.1:18080 (control) and 127.0.0.1:9100 (compute) ports, and a local
# python3 release endpoint serving fixture tarballs generated by a small
# deterministic builder. No root is required; the script SKIPs with an
# explicit message when a prerequisite is missing (mirroring
# tests/doctor-process.sh and tests/installer-negative.sh).
#
# Engine-interface contract (kept in sync with the Rust implementation;
# see docs/plan/o3k-upgrade.md):
#   - release resolution/download goes through the PATH `curl` shim, which
#     rewrites github.com/api.github.com URLs onto the local fixture endpoint
#     (the same SystemExec seam the doctor uses). If the engine later adopts
#     an internal HTTP client for downloads, it must honor an equivalent
#     override so this test stays offline.
#   - the concurrent-invocation lock is `<state-file>.lock` (O_EXCL with
#     dead-pid reclaim — the engine's unsafe-free equivalent of the plan §2
#     flock; the test pre-creates it with a live pid).
#   - `upgrade --check` is read-only; `--yes` keeps mutation cases
#     noninteractive; `--json` emits the plan §1 document
#     (source_version, target_version, phase, backup_id, status,
#     rollback_performed, doctor_status).
#   - COMMITTED clears the in-progress state file and records the backup in
#     <backup-dir>/backup-chain.json (plan §2).
#
# Every case asserts three things: the exit code, the state file
# phase/status (absent counts as a pinned assertion where the plan clears
# it), and that no foreign fixture file was modified (byte-level snapshot of
# binaries, manifests, config, and database).
set -Eeuo pipefail
umask 0022

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK_DIR="$(mktemp -d "${TMPDIR:-/tmp}/o3k-upgrade-process.XXXXXX")"
chmod 0755 "$WORK_DIR" # unprivileged engine runs must be able to traverse it
OUT_DIR="$WORK_DIR/outputs"
mkdir -p "$OUT_DIR"
SERVER_PIDS=()
PASS=0
FAIL=0
SKIP=0

cleanup() {
  local pid
  for pid in "${SERVER_PIDS[@]}"; do kill "$pid" 2>/dev/null || true; done
  if [[ "${O3K_UPGRADE_TEST_KEEP:-0}" != 1 ]]; then
    rm -rf -- "$WORK_DIR"
  else
    printf 'kept work dir: %s\n' "$WORK_DIR" >&2
  fi
}
trap cleanup EXIT

record_pass() { PASS=$((PASS + 1)); printf 'ok   %s\n' "$1"; }
record_fail() { FAIL=$((FAIL + 1)); printf 'FAIL %s\n' "$1"; }
record_skip() { SKIP=$((SKIP + 1)); printf 'skip %s\n' "$1"; }

for tool in python3 tar sha256sum mktemp grep sed strings sort; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    record_skip "upgrade-process tests need $tool"
    printf 'upgrade process tests: %d passed, %d failed, %d skipped\n' "$PASS" "$FAIL" "$SKIP"
    exit 0
  fi
done

free_port() {
  python3 -c 'import socket; s = socket.socket(); s.bind(("127.0.0.1", 0)); print(s.getsockname()[1]); s.close()'
}

