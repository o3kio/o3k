# snapshot_fixture DIR OUT — sha256 of every file under the install fixture
# (prefix, config, data only; engine outputs like state/backups/download/logs
# are asserted separately), the byte-level no-mutation reference.
snapshot_fixture() {
  # SQLite WAL sidecars are transient by design (created/removed on
  # connection open/close), so they are excluded from the byte-level
  # no-mutation reference.
  (cd "$1" && find ./prefix ./config ./data -type f \
    ! -name 'o3k.sqlite-wal' ! -name 'o3k.sqlite-shm' \
    -print0 | sort -z | xargs -0 sha256sum | sha256sum | awk '{print $1}')
}

# db_schema_version DB — max applied _sqlx_migrations version (the §7 ruler).
db_schema_version() {
  python3 - "$1" <<'PY'
import sqlite3
import sys

connection = sqlite3.connect(sys.argv[1])
try:
    rows = connection.execute(
        "SELECT COALESCE(MAX(version), 0) FROM _sqlx_migrations"
    ).fetchall()
except sqlite3.Error:
    raise SystemExit("unreadable")
print(rows[0][0])
connection.close()
PY
}

# json_assert DESC FILE EXPECTED — python3 helper for JSON document
# assertions. EXPECTED is a JSON object whose keys may be dot-paths into the
# document; each must be present and equal. A missing FILE fails.
json_assert() {
  python3 - "$1" "$2" "$3" <<'PY'
import json
import sys

desc, path, expected_text = sys.argv[1], sys.argv[2], sys.argv[3]
try:
    document = json.load(open(path, encoding="utf-8"))
except Exception as error:
    print(f"FAIL {desc} ({path} is not parseable JSON: {error})")
    raise SystemExit(1)
expected = json.loads(expected_text)
mismatches = []
for dotted, wanted in expected.items():
    node = document
    for key in dotted.split("."):
        if isinstance(node, dict) and key in node:
            node = node[key]
        else:
            node = None
            break
    if node != wanted:
        mismatches.append(f"{dotted}: expected {wanted!r}, got {node!r}")
if mismatches:
    print(f"FAIL {desc} ({'; '.join(mismatches)}; document: {document!r})")
    raise SystemExit(1)
print(f"ok   {desc}")
PY
}

# json_refute DESC FILE EXPECTED — python3 helper asserting that each dotted
# key is ABSENT from the document or differs from the given value. Used to
# pin "state is not committed" without guessing the exact terminal phase.
json_refute() {
  python3 - "$1" "$2" "$3" <<'PY'
import json
import sys

desc, path, expected_text = sys.argv[1], sys.argv[2], sys.argv[3]
document = json.load(open(path, encoding="utf-8"))
expected = json.loads(expected_text)
violations = []
for dotted, forbidden in expected.items():
    node = document
    for key in dotted.split("."):
        if isinstance(node, dict) and key in node:
            node = node[key]
        else:
            node = None
            break
    if node == forbidden:
        violations.append(f"{dotted}: forbidden value {forbidden!r} present")
if violations:
    print(f"FAIL {desc} ({'; '.join(violations)}; document: {document!r})")
    raise SystemExit(1)
print(f"ok   {desc}")
PY
}

