# curl: rewrites GitHub release/API URLs onto the local fixture endpoint and
# delegates everything else (including the rewritten URL) to the real curl.
cat >"$SHIM_BIN/curl" <<'EOF'
#!/usr/bin/env bash
# TEST FIXTURE — URL rewriting proxy around the real curl. The fixture
# endpoint is served by the test's own python3 http.server; no external
# network is ever contacted by a successful rewrite.
url=""
rewritten=""
for arg in "$@"; do
  case "$arg" in
    http://*|https://*) url="$arg" ;;
  esac
done
if [ -n "$url" ]; then
  case "$url" in
    https://api.github.com/repos/o3kio/o3k/*)
      rewritten="${O3K_TEST_ENDPOINT:?}/api/${url#https://api.github.com/repos/o3kio/o3k/}" ;;
    https://github.com/o3kio/o3k/releases/download/*)
      rewritten="${O3K_TEST_ENDPOINT:?}/releases/${url#https://github.com/o3kio/o3k/releases/download/}" ;;
    https://github.com/o3kio/o3k/releases/*)
      rewritten="${O3K_TEST_ENDPOINT:?}/releases/${url#https://github.com/o3kio/o3k/releases/}" ;;
    *) rewritten="$url" ;;
  esac
fi
out=()
for arg in "$@"; do
  if [ -n "$rewritten" ] && [ "$arg" = "$url" ]; then out+=("$rewritten"); else out+=("$arg"); fi
done
exec /usr/bin/curl "${out[@]}"
EOF

