# systemctl: stateful fake recording every stop/start in a per-case log and
# tracking active units in a per-case state dir. Both units start ACTIVE for
# a healthy sandbox; stop/start flip them.
cat >"$SHIM_BIN/systemctl" <<'EOF'
#!/usr/bin/env bash
# TEST FIXTURE — stateful fake systemctl; never touches the real host.
log() { printf '%s\n' "$*" >>"${O3K_TEST_SYSTEMCTL_LOG:?}"; }
case "$*" in
  *is-active*o3kd.service*)
    if [ -f "${O3K_TEST_SYSTEMCTL_STATE:?}/o3kd.active" ]; then printf 'active\n'; exit 0; else exit 3; fi ;;
  *is-active*o3k-compute.service*)
    if [ -f "${O3K_TEST_SYSTEMCTL_STATE:?}/compute.active" ]; then printf 'active\n'; exit 0; else exit 3; fi ;;
  *stop*o3k-compute.service*) log "$*"; rm -f "${O3K_TEST_SYSTEMCTL_STATE:?}/compute.active"; exit 0 ;;
  *stop*o3kd.service*) log "$*"; rm -f "${O3K_TEST_SYSTEMCTL_STATE:?}/o3kd.active"; exit 0 ;;
  *start*o3kd.service*) log "$*"; touch "${O3K_TEST_SYSTEMCTL_STATE:?}/o3kd.active"; exit 0 ;;
  *start*o3k-compute.service*) log "$*"; touch "${O3K_TEST_SYSTEMCTL_STATE:?}/compute.active"; exit 0 ;;
  *) log "$*"; exit 0 ;;
esac
EOF

