  export O3K_TEST_DF_MODE=tiny
  set +e
  run_engine "$case_dir" "$OUT_DIR/case9.out" "$OUT_DIR/case9.err" upgrade --to "v$TARGET_VERSION" --yes --json
  set -e
  if [[ "$(case_exit "$case_dir")" -eq 1 ]]; then
    record_pass "insufficient disk refused at preflight (exit 1)"
  else
    record_fail "insufficient disk was not refused (exit $(case_exit "$case_dir"))"
  fi
  [[ -z "$(find "$case_dir/backups" -mindepth 1 -print -quit 2>/dev/null || true)" ]] \
    && record_pass "insufficient disk produced no backup" \
    || record_fail "insufficient disk produced a backup"
  if [[ "$(snapshot_fixture "$case_dir")" = "$(cat "$case_dir/snapshot.before")" ]]; then
    record_pass "insufficient disk mutated nothing"
  else
    record_fail "insufficient disk modified a fixture file"
  fi
  unset O3K_TEST_DF_MODE

  # 10. interrupted backup: the backup directory path is blocked by a
  #     regular file (root-proof: mkdir through a file fails for everyone),
  #     so the backup phase fails -> no mutation after, terminal state.
  case_dir="$(new_case backup-fails)"
  printf 'blocks the backup directory\n' >"$case_dir/backups"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case10.out" "$OUT_DIR/case10.err" upgrade --to "v$TARGET_VERSION" --yes --json
  set -e
  if [[ "$(case_exit "$case_dir")" -eq 1 ]]; then
    record_pass "backup failure aborts the upgrade (exit 1)"
  else
    record_fail "backup failure was not aborted (exit $(case_exit "$case_dir"))"
  fi
  [[ "$(cat "$case_dir/backups")" = "blocks the backup directory" ]] \
    && record_pass "failed backup wrote no backup content" \
    || record_fail "failed backup replaced the blocking file with backup content"
  if [[ "$(snapshot_fixture "$case_dir")" = "$(cat "$case_dir/snapshot.before")" ]]; then
    record_pass "backup failure mutated nothing"
  else
    record_fail "backup failure modified a fixture file"
  fi
  if [[ -e "$case_dir/state.json" ]]; then
    json_refute "backup failure leaves a non-committed terminal state" \
      "$case_dir/state.json" '{"status": "committed"}'
  else
    record_pass "backup failure cleared the state file"
  fi

  # 11. interrupted binary switch: the last-switched binary target is an
  #     un-renameable non-empty directory, so the switch fails partway and
  #     the old binary set is restored.
  case_dir="$(new_case switch-fails)"
  rm -f "$case_dir/prefix/bin/o3k"
  mkdir -p "$case_dir/prefix/bin/o3k"
  printf 'blocks rename\n' >"$case_dir/prefix/bin/o3k/blocker"
  o3kd_before="$(sha256sum "$case_dir/prefix/bin/o3kd" | awk '{print $1}')"
  compute_before="$(sha256sum "$case_dir/prefix/bin/o3k-compute" | awk '{print $1}')"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case11.out" "$OUT_DIR/case11.err" upgrade --to "v$TARGET_VERSION" --yes --json
  set -e
  if [[ "$(case_exit "$case_dir")" -eq 1 ]]; then
    record_pass "interrupted binary switch aborts (exit 1)"
  else
    record_fail "interrupted binary switch was not aborted (exit $(case_exit "$case_dir"))"
  fi
  if [[ "$(sha256sum "$case_dir/prefix/bin/o3kd" | awk '{print $1}')" = "$o3kd_before" \
    && "$(sha256sum "$case_dir/prefix/bin/o3k-compute" | awk '{print $1}')" = "$compute_before" ]]; then
    record_pass "old binary set restored after the interrupted switch"
  else
    record_fail "a binary was left modified after the interrupted switch"
  fi
  if [[ -e "$case_dir/state.json" ]]; then
    json_refute "interrupted switch leaves a non-committed terminal state" \
      "$case_dir/state.json" '{"status": "committed"}'
  else
    # A preflight refusal of the un-renameable binary target is the same
    # safety property (old binaries intact, nothing committed).
    record_pass "interrupted switch refused at preflight (no state, no mutation)"
  fi

  # 12. migration failure: the target manifest declares schema_version 99
  #     while the (fake) o3kd start does not advance the DB -> rollback
  #     attempted, old binaries and DB restored.
  case_dir="$(new_case migration-fails)"
  printf 'list=releases\nsha=normal\nserve=on\nschema=99\n' >"$ENDPOINT_MODE"
  
  set +e
  run_engine "$case_dir" "$OUT_DIR/case12.out" "$OUT_DIR/case12.err" upgrade --to "v$TARGET_VERSION" --yes --json
  set -e
  if [[ "$(case_exit "$case_dir")" -eq 1 ]]; then
    record_pass "migration failure aborts the upgrade (exit 1)"
  else
    record_fail "migration failure was not aborted (exit $(case_exit "$case_dir"))"
  fi
  if [[ "$(db_schema_version "$case_dir/data/o3k.sqlite")" = "$SCHEMA_VERSION" ]] \
    && python3 - "$case_dir/data/o3k.sqlite" <<'PY'
import sqlite3
import sys

connection = sqlite3.connect(sys.argv[1])
rows = connection.execute(
    "SELECT COUNT(*) FROM placement_providers WHERE id = 'provider-1'"
).fetchall()
assert rows[0][0] == 1, "placement row lost"
PY
  then
    record_pass "migration failure left the pre-upgrade database intact"
  else
    record_fail "migration failure damaged the database"
  fi
  if [[ "$(cat "$case_dir/prefix/bin/o3kd")" = "fixture installed binary o3kd $INSTALLED_VERSION" ]]; then
    record_pass "migration failure restored the old binary set"
  else
    record_fail "migration failure left the new binaries installed"
  fi
  if [[ -z "$(find "$case_dir/backups" -mindepth 1 -print -quit 2>/dev/null || true)" ]]; then
    record_fail "migration failure recorded no backup (rollback evidence expected)"
  else
    record_pass "migration failure recorded the backup for recovery"
  fi
  if grep -Eqi 'rollback' "$OUT_DIR/case12.out" "$OUT_DIR/case12.err"; then
    record_pass "migration failure reports the rollback"
  else
    record_fail "migration failure output does not mention the rollback"
  fi

  # 13. doctor failure after start: unhealthy control-plane shim -> not
  #     committed, rollback to the old binaries.
  case_dir="$(new_case doctor-fails)"
  printf 'list=releases\nsha=normal\nserve=on\nschema=normal\n' >"$ENDPOINT_MODE"
  
  printf 'unhealthy\n' >"$CONTROL_HEALTH"
  export O3K_TEST_DOCTOR_SHIM_MODE=unhealthy
  set +e
  run_engine "$case_dir" "$OUT_DIR/case13.out" "$OUT_DIR/case13.err" upgrade --to "v$TARGET_VERSION" --yes --json
  set -e
  printf 'healthy\n' >"$CONTROL_HEALTH"
  unset O3K_TEST_DOCTOR_SHIM_MODE
  if [[ "$(case_exit "$case_dir")" -eq 1 ]]; then
    record_pass "doctor failure after start aborts the upgrade (exit 1)"
  else
    record_fail "doctor failure after start was not aborted (exit $(case_exit "$case_dir"))"
  fi
  if [[ "$(cat "$case_dir/prefix/bin/o3kd")" = "fixture installed binary o3kd $INSTALLED_VERSION" ]]; then
    record_pass "doctor failure rolled back to the old binary set"
  else
    record_fail "doctor failure left the new binaries installed"
  fi
  if [[ -e "$case_dir/state.json" ]]; then
    json_refute "doctor failure leaves a non-committed terminal state" \
      "$case_dir/state.json" '{"status": "committed"}'
  else
    record_pass "doctor failure cleared the state file after the rollback"
  fi

  # 14. rollback with no valid backup -> refused.
  case_dir="$(new_case rollback-no-backup)"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case14.out" "$OUT_DIR/case14.err" rollback --yes --json
  set -e
  if [[ "$(case_exit "$case_dir")" -eq 1 ]] \
    && grep -Eqi 'backup|rollback' "$OUT_DIR/case14.out" "$OUT_DIR/case14.err"; then
    record_pass "rollback with no valid backup refused (exit 1)"
  else
    record_fail "rollback with no backup was not refused (exit $(case_exit "$case_dir"); see $OUT_DIR/case14.err)"
  fi
  if [[ "$(snapshot_fixture "$case_dir")" = "$(cat "$case_dir/snapshot.before")" ]]; then
    record_pass "rollback with no backup mutated nothing"
  else
    record_fail "rollback with no backup modified a fixture file"
  fi

  # 15. rollback with a tampered backup (flipped byte in backup.json) ->
  #     refused, the committed install stays untouched.
  case_dir="$(new_case rollback-tampered)"
  printf 'list=releases\nsha=normal\nserve=on\nschema=normal\n' >"$ENDPOINT_MODE"
  
  set +e
  run_engine "$case_dir" "$OUT_DIR/case15-up.out" "$OUT_DIR/case15-up.err" upgrade --to "v$TARGET_VERSION" --yes --json
  up_status=$?
  set -e
  if [[ "$up_status" -eq 0 ]]; then
    record_pass "tamper case: initial upgrade committed (exit 0)"
  else
    record_fail "tamper case: initial upgrade failed (exit $up_status; see $OUT_DIR/case15-up.err)"
  fi
  backup_json="$(find "$case_dir/backups" -name backup.json -print -quit 2>/dev/null || true)"
  [[ -n "$backup_json" && -s "$backup_json" ]] \
    && record_pass "tamper case: a backup record exists" \
    || record_fail "tamper case: no backup record found"
  if [[ -n "$backup_json" ]]; then
    sed -i 's/"source_version"/"source_version_corrupted"/' "$backup_json" # the record must fail validation
    set +e
    run_engine "$case_dir" "$OUT_DIR/case15.out" "$OUT_DIR/case15.err" rollback --yes --json
    set -e
    if [[ "$(case_exit "$case_dir")" -eq 1 ]]; then
      record_pass "rollback with a tampered backup refused (exit 1)"
    else
      record_fail "rollback accepted a tampered backup (exit $(case_exit "$case_dir"))"
    fi
    if [[ "$(cat "$case_dir/prefix/bin/o3kd")" = "fixture release binary o3kd $TARGET_VERSION" ]]; then
      record_pass "tampered-backup rollback left the committed install untouched"
    else
      record_fail "tampered-backup rollback modified the committed binaries"
    fi
  fi

  # 16. second rollback -> no-op notice, no mutation.
  case_dir="$(new_case second-rollback)"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case16-up.out" "$OUT_DIR/case16-up.err" upgrade --to "v$TARGET_VERSION" --yes --json
  up_status=$?
  set -e
  [[ "$up_status" -eq 0 ]] || record_fail "second-rollback case: initial upgrade failed (exit $up_status)"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case16-rb.out" "$OUT_DIR/case16-rb.err" rollback --yes --json
  rb_status=$?
  set -e
  [[ "$rb_status" -eq 0 ]] || record_fail "second-rollback case: first rollback failed (exit $rb_status)"
  snapshot_after_rollback="$(snapshot_fixture "$case_dir")"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case16.out" "$OUT_DIR/case16.err" rollback --yes --json
  set -e
  status16="$(case_exit "$case_dir")"
  if [[ "$status16" -eq 0 || "$status16" -eq 1 ]] \
    && grep -Eqi 'rollback|backup' "$OUT_DIR/case16.out" "$OUT_DIR/case16.err"; then
    record_pass "second rollback is a no-op with a notice (exit $status16)"
  else
    record_fail "second rollback behaved unexpectedly (exit $status16; see $OUT_DIR/case16.err)"
  fi
  if [[ "$(snapshot_fixture "$case_dir")" = "$snapshot_after_rollback" ]]; then
    record_pass "second rollback mutated nothing"
  else
    record_fail "second rollback modified a fixture file"
  fi

  # 17. concurrent upgrade: the engine's lock file (<state-file>.lock,
  #     O_EXCL with dead-pid reclaim) is pre-created with a live pid, a
  #     second invocation must refuse.
  case_dir="$(new_case concurrent)"
  LOCK_FILE="$case_dir/state.json.lock"
  printf '%s\n' "$$" >"$LOCK_FILE"
  set +e
  O3K_UPGRADE_PREFIX="$case_dir/prefix" \
  O3K_UPGRADE_BIN_DIR="$case_dir/prefix/bin" \
  O3K_UPGRADE_CONFIG_DIR="$case_dir/config" \
  O3K_UPGRADE_DATA_DIR="$case_dir/data" \
  O3K_UPGRADE_STATE_FILE="$case_dir/state.json" \
  O3K_UPGRADE_BACKUP_DIR="$case_dir/backups" \
  O3K_UPGRADE_DOWNLOAD_DIR="$case_dir/download" \
  O3K_UPGRADE_RELEASES_URL="http://127.0.0.1:$ENDPOINT_PORT/api/" \
  O3K_UPGRADE_ASSUME_ROOT=1 \
  O3K_UPGRADE_DOCTOR_RETRY_ATTEMPTS=2 \
  O3K_UPGRADE_DOCTOR_RETRY_DELAY_MS=50 \
  O3K_DOCTOR_CONFIG_DIR="$case_dir/config" \
  O3K_DOCTOR_DATA_DIR="$case_dir/data" \
  O3K_DOCTOR_PREFIX="$case_dir/prefix" \
  O3K_TEST_ENDPOINT="http://127.0.0.1:$ENDPOINT_PORT" \
  O3K_TEST_SYSTEMCTL_LOG="$case_dir/systemctl.log" \
  O3K_TEST_SYSTEMCTL_STATE="$case_dir/systemctl-state" \
  O3K_TEST_SCRIPT_LOG="$case_dir/scripts.log" \
  PATH="$SHIM_BIN:$PATH" \
  timeout 20 "$BIN" upgrade --to "v$TARGET_VERSION" --yes --json \
    >"$OUT_DIR/case17.out" 2>"$OUT_DIR/case17.err"
  status17=$?
  set -e
  printf '%d' "$status17" >"$case_dir/exit"
  rm -f "$LOCK_FILE"
  # 1 = explicit concurrent refusal (also accepts 124 for a bounded wait).
  if [[ "$status17" -eq 1 || "$status17" -eq 124 ]]; then
    record_pass "concurrent upgrade refused while the lock is held (exit $status17)"
  else
    record_fail "concurrent upgrade was not refused (exit $status17; see $OUT_DIR/case17.err)"
  fi
  if [[ "$(snapshot_fixture "$case_dir")" = "$(cat "$case_dir/snapshot.before")" ]]; then
    record_pass "concurrent upgrade mutated nothing"
  else
    record_fail "concurrent upgrade modified a fixture file"
  fi

  # 18. happy path: full upgrade -> rollback -> re-upgrade with all shims
  #     healthy; state COMMITTED, service order correct, and the fixture
  #     identity (config files, DB rows) preserved end-to-end.
  case_dir="$(new_case happy-path)"
  printf 'list=releases\nsha=normal\nserve=on\nschema=normal\n' >"$ENDPOINT_MODE"
  
  config_before="$(cd "$case_dir/config" && find . -type f -print0 | sort -z | xargs -0 sha256sum | sha256sum | awk '{print $1}')"
  set +e
  run_engine "$case_dir" "$OUT_DIR/case18-up.out" "$OUT_DIR/case18-up.err" upgrade --to "v$TARGET_VERSION" --yes --json
  up_status=$?
  set -e
  if [[ "$up_status" -eq 0 ]]; then
    record_pass "happy path: upgrade committed (exit 0)"
  else
    record_fail "happy path: upgrade failed (exit $up_status; see $OUT_DIR/case18-up.out, $OUT_DIR/case18-up.err)"
  fi
  if python3 - "$case_dir" "$INSTALLED_VERSION" "$TARGET_VERSION" <<'PY'
import hashlib
import pathlib
import sys

case_dir = pathlib.Path(sys.argv[1])
installed, target = sys.argv[2], sys.argv[3]
prefix = case_dir / "prefix"

def read(path):
    return path.read_bytes()

old_binary = f"fixture installed binary o3kd {installed}\n".encode()
new_binary = f"fixture release binary o3kd {target}\n".encode()
assert read(prefix / "bin/o3kd") == new_binary, "o3kd was not switched"
assert read(prefix / "bin/o3k") == f"fixture release binary o3k {target}\n".encode(), "o3k was not switched"
assert read(prefix / "bin/o3k-compute") == f"fixture release binary o3k-compute {target}\n".encode(), "o3k-compute was not switched"
import json

manifest = json.loads(read(prefix / "share/o3k/release-manifest.json"))
assert manifest["version"] == target, manifest
PY
  then
    record_pass "happy path: new binaries + release manifest installed"
  else
    record_fail "happy path: binaries or release manifest are wrong after upgrade"
  fi
  [[ ! -e "$case_dir/state.json" ]] \
    && record_pass "happy path: committed upgrade cleared the in-progress state" \
    || record_fail "happy path: upgrade left an in-progress state file"
  if [[ -s "$case_dir/backups/backup-chain.json" ]] \
    && python3 - "$case_dir/backups/backup-chain.json" <<'PY'
import json
import sys

document = json.load(open(sys.argv[1], encoding="utf-8"))
entries = document.get("backups", document if isinstance(document, list) else [])
assert len(entries) >= 1, "chain has no entries"
PY
  then
    record_pass "happy path: backup chain records the committed backup"
  else
    record_fail "happy path: backup chain missing or empty"
  fi
  if [[ "$(db_schema_version "$case_dir/data/o3k.sqlite")" = "$SCHEMA_VERSION" ]] \
    && python3 - "$case_dir/data/o3k.sqlite" <<'PY'
import sqlite3
import sys

connection = sqlite3.connect(sys.argv[1])
rows = connection.execute(
    "SELECT COUNT(*) FROM placement_providers WHERE id = 'provider-1'"
).fetchall()
assert rows[0][0] == 1, "placement row lost"
PY
  then
    record_pass "happy path: database identity preserved (schema + placement rows)"
  else
    record_fail "happy path: database identity damaged"
  fi
  if grep -q '^stop o3k-compute' "$case_dir/systemctl.log" \
    && grep -q '^stop o3kd' "$case_dir/systemctl.log" \
    && grep -q '^start o3kd' "$case_dir/systemctl.log" \
    && grep -q '^start o3k-compute' "$case_dir/systemctl.log"; then
    compute_stop="$(grep -n '^stop o3k-compute' "$case_dir/systemctl.log" | head -n1 | cut -d: -f1)"
    control_stop="$(grep -n '^stop o3kd' "$case_dir/systemctl.log" | head -n1 | cut -d: -f1)"
    control_start="$(grep -n '^start o3kd' "$case_dir/systemctl.log" | head -n1 | cut -d: -f1)"
    compute_start="$(grep -n '^start o3k-compute' "$case_dir/systemctl.log" | head -n1 | cut -d: -f1)"
    if [[ "$compute_stop" -lt "$control_stop" && "$control_stop" -lt "$control_start" \
      && "$control_start" -lt "$compute_start" ]]; then
      record_pass "happy path: service order is compute-stop -> o3kd-stop -> o3kd-start -> compute-start"
    else
      record_fail "happy path: service stop/start order violated (see $case_dir/systemctl.log)"
    fi
  else
    record_fail "happy path: systemctl shim did not record the stop/start sequence"
  fi
  if [[ "$(cd "$case_dir/config" && find . -type f -print0 | sort -z | xargs -0 sha256sum | sha256sum | awk '{print $1}')" = "$config_before" ]]; then
    record_pass "happy path: config identity (env files, credentials, TLS) preserved through upgrade"
  else
    record_fail "happy path: a configuration file changed during the upgrade"
  fi

  # 18 continued: rollback.
  set +e
  run_engine "$case_dir" "$OUT_DIR/case18-rb.out" "$OUT_DIR/case18-rb.err" rollback --yes --json
  rb_status=$?
  set -e
  if [[ "$rb_status" -eq 0 ]]; then
    record_pass "happy path: rollback succeeds (exit 0)"
  else
    record_fail "happy path: rollback failed (exit $rb_status; see $OUT_DIR/case18-rb.err)"
  fi
  if python3 - "$case_dir" "$INSTALLED_VERSION" <<'PY'
import pathlib
import sys

case_dir = pathlib.Path(sys.argv[1])
installed = sys.argv[2]
prefix = case_dir / "prefix"
assert prefix.joinpath("bin/o3kd").read_bytes() == f"fixture installed binary o3kd {installed}\n".encode()
PY
  then
    record_pass "happy path: rollback restored the old binary set"
  else
    record_fail "happy path: rollback did not restore the old binaries"
  fi
  if python3 - "$case_dir/data/o3k.sqlite" <<'PY'
import sqlite3
import sys

connection = sqlite3.connect(sys.argv[1])
rows = connection.execute(
    "SELECT COUNT(*) FROM placement_providers WHERE id = 'provider-1'"
).fetchall()
assert rows[0][0] == 1, "placement row lost"
PY
  then
    record_pass "happy path: rollback preserved the database"
  else
    record_fail "happy path: rollback damaged the database"
  fi

  # 18 continued: re-upgrade proves upgrade-after-rollback.
  set +e
  run_engine "$case_dir" "$OUT_DIR/case18-re.out" "$OUT_DIR/case18-re.err" upgrade --to "v$TARGET_VERSION" --yes --json
  re_status=$?
  set -e
  if [[ "$re_status" -eq 0 ]] \
    && [[ "$(cat "$case_dir/prefix/bin/o3kd")" = "fixture release binary o3kd $TARGET_VERSION" ]]; then
    record_pass "happy path: re-upgrade after rollback succeeds"
  else
    record_fail "happy path: re-upgrade failed (exit $re_status; see $OUT_DIR/case18-re.err)"
  fi
  [[ ! -e "$case_dir/state.json" ]] \
    && record_pass "happy path: re-upgrade ended COMMITTED (state cleared)" \
    || record_fail "happy path: re-upgrade left an in-progress state file"
  if [[ "$(cd "$case_dir/config" && find . -type f -print0 | sort -z | xargs -0 sha256sum | sha256sum | awk '{print $1}')" = "$config_before" ]]; then
    record_pass "happy path: config identity preserved through upgrade + rollback + re-upgrade"
  else
    record_fail "happy path: a configuration file changed across the full journey"
  fi
  grep -Fqx 'foreign canary — must never change' "$case_dir/data/foreign-canary" \
    && record_pass "happy path: foreign fixture file untouched" \
    || record_fail "happy path: foreign fixture file modified"
fi

# Secret-safety: no output may ever carry the sandbox sentinel.
if grep -rq "$SENTINEL" "$OUT_DIR" 2>/dev/null; then
  record_fail "a sentinel secret leaked into captured output"
  grep -rn "$SENTINEL" "$OUT_DIR" >&2 || true
else
  record_pass "no sentinel secret appears in any captured output"
fi

printf 'upgrade process tests: %d passed, %d failed, %d skipped\n' "$PASS" "$FAIL" "$SKIP"
[[ $FAIL -eq 0 ]]
