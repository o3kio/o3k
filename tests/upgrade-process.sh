# build_sandbox DIR — a complete healthy fixture install of v0.2.0-alpha.2
# under DIR (prefix/bin with real SHA256SUMS, /etc/o3k-style config with a
# complete mTLS identity, WAL SQLite with _sqlx_migrations up to 0017 and
# placement/epoch rows, compute network ownership, a foreign canary that must
# never change, and active systemctl units).
build_sandbox() {
  local dir="$1" prefix config data
  prefix="$dir/prefix"
